"""Operational store: source truth, consent and commercial action. Every tenant-owned row carries merchant_id.

Two backends, one schema:
- PostgreSQL when DATABASE_URL is set (production). Tenant tables have row-level security: inside a request scoped
  to one business (see `tenant`), the database itself only returns and accepts that business's rows.
- SQLite otherwise (local runs and tests): one file, WAL.

Migrations in migrations/ run on both; files ending in .pg.sql run on PostgreSQL only. The analytical warehouse is
separate (DuckDB) and is rebuilt from this store's extract by refresh.py.
"""
from __future__ import annotations

import contextlib
import contextvars
import datetime
import json
import os
import re
import sqlite3
import threading
from pathlib import Path

from .config import VAR

_lock = threading.RLock()
_db = None
_applied_scope = None  # the tenant scope last set on the PostgreSQL connection
MIGRATIONS = Path(__file__).parent / "migrations"
DATABASE_URL = os.environ.get("DATABASE_URL", "")
BACKEND = "postgres" if DATABASE_URL.startswith(("postgres://", "postgresql://")) else "sqlite"
TENANT_TABLES = ("merchants", "merchant_users", "merchant_connections", "consent_grants", "catalog_items", "orders", "payment_events", "fulfillment_events", "source_evidence", "credentials", "checkout_sessions", "coach_actions", "seal_withdrawals")

# '' = no scope (system work: refresh, webhooks, public pages); a merchant id = that business only.
_scope: contextvars.ContextVar[str] = contextvars.ContextVar("rds_tenant_scope", default="")


@contextlib.contextmanager
def tenant(merchant_id: str):
    """Run the block as one business: on PostgreSQL, row-level security hides every other business's rows."""
    token = _scope.set(merchant_id)
    try:
        yield
    finally:
        _scope.reset(token)


@contextlib.contextmanager
def system():
    """Run the block with no tenant scope (the nightly refresh, cross-business checks such as SKU ownership)."""
    token = _scope.set("")
    try:
        yield
    finally:
        _scope.reset(token)


def unscoped(fn):
    """Decorator: the function always runs as system work (the refresh reads every business to rebuild the warehouse)."""
    import functools

    @functools.wraps(fn)
    def wrapper(*a, **kw):
        with system():
            return fn(*a, **kw)
    return wrapper


def scope() -> str:
    return _scope.get()


def _pg_sql(sql: str) -> str:
    sql = re.sub(r"INSERT OR IGNORE INTO (.+)$", r"INSERT INTO \1 ON CONFLICT DO NOTHING", sql, flags=re.S)
    sql = sql.replace("BEGIN IMMEDIATE", "BEGIN").replace("%", "%%")
    return sql.replace("?", "%s")


def _pg_migration(text: str) -> str:
    return text.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")


def _params(params):
    return [int(p) if isinstance(p, bool) else p for p in params]


def _migrations() -> list[Path]:
    files = sorted(MIGRATIONS.glob("*.sql"))
    return [f for f in files if BACKEND == "postgres" or not f.name.endswith(".pg.sql")]


def db():
    global _db
    with _lock:
        if _db is None:
            if BACKEND == "postgres":
                import psycopg
                from psycopg.rows import dict_row
                conn = psycopg.connect(DATABASE_URL, autocommit=True, row_factory=dict_row)
                conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)")
                done = {r["name"] for r in conn.execute("SELECT name FROM schema_migrations")}
                for f in _migrations():
                    if f.name not in done:
                        with conn.transaction():
                            conn.execute(_pg_migration(f.read_text()))
                            conn.execute("INSERT INTO schema_migrations VALUES (%s, %s)", [f.name, now()])
            else:
                conn = sqlite3.connect(VAR / "ops.sqlite", check_same_thread=False, isolation_level=None)
                conn.row_factory = sqlite3.Row
                conn.execute("PRAGMA journal_mode=WAL")
                conn.execute("PRAGMA foreign_keys=ON")
                conn.execute("CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)")
                done = {r[0] for r in conn.execute("SELECT name FROM schema_migrations")}
                for f in _migrations():
                    if f.name not in done:
                        conn.executescript("BEGIN;" + f.read_text() + "COMMIT;")
                        conn.execute("INSERT INTO schema_migrations VALUES (?,?)", [f.name, now()])
            _db = conn
        return _db


def _execute(sql: str, params=()):
    """Run one statement under the lock, after applying the caller's tenant scope (PostgreSQL)."""
    global _applied_scope
    conn = db()
    if BACKEND == "postgres":
        want = _scope.get()
        if want != _applied_scope:
            conn.execute("SELECT set_config('app.merchant_id', %s, false)", [want])
            _applied_scope = want
        return conn.execute(_pg_sql(sql), _params(params))
    return conn.execute(sql, _params(params))


def now() -> str:
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0).isoformat()


def today() -> str:
    return datetime.datetime.now(datetime.timezone.utc).date().isoformat()


def q(sql: str, params=()) -> list[dict]:
    with _lock:
        return [dict(r) for r in _execute(sql, params)]


def one(sql: str, params=()) -> dict | None:
    r = q(sql, params)
    return r[0] if r else None


def run(sql: str, params=()) -> int:
    with _lock:
        return _execute(sql, params).rowcount


def insert(table: str, row: dict, or_ignore: bool = False) -> bool:
    cols = ", ".join(row)
    with _lock:
        cur = _execute(f"INSERT {'OR IGNORE ' if or_ignore else ''}INTO {table} ({cols}) VALUES ({', '.join('?' * len(row))})",
                       [json.dumps(v) if isinstance(v, (list, dict)) else v for v in row.values()])
        return cur.rowcount == 1


class transaction:
    """All-or-nothing block for multi-row writes (an import, an order with its events)."""

    def __enter__(self):
        _lock.acquire()
        _execute("BEGIN IMMEDIATE")

    def __exit__(self, exc_type, *a):
        try:
            _execute("ROLLBACK" if exc_type else "COMMIT")
        finally:
            _lock.release()


def health() -> dict:
    """What the deep health check reports: backend, migrations applied versus shipped, and row-level security."""
    expected = [f.name for f in _migrations()]
    with system():
        applied = sorted(r["name"] for r in q("SELECT name FROM schema_migrations"))
        out = {"backend": BACKEND, "migrations_expected": expected, "migrations_applied": applied,
               "schema_current": applied == sorted(expected), "row_level_security": None}
        if BACKEND == "postgres":
            rows = q("SELECT relname, relrowsecurity, relforcerowsecurity FROM pg_class WHERE relname = ANY(?)", [list(TENANT_TABLES)])
            out["row_level_security"] = {r["relname"]: bool(r["relrowsecurity"] and r["relforcerowsecurity"]) for r in rows}
    return out


def audit(actor: str, action: str, target: str = "", result: str = "ok", detail: dict | None = None, merchant_id: str | None = None):
    insert("audit_events", {"at": now(), "actor": actor, "merchant_id": merchant_id, "action": action, "target": target,
                            "result": result, "detail": json.dumps(detail or {})})


def recent_audit(limit: int = 50, merchant_id: str | None = None) -> list[dict]:
    if merchant_id:
        return q("SELECT * FROM audit_events WHERE merchant_id = ? ORDER BY id DESC LIMIT ?", [merchant_id, limit])
    return q("SELECT * FROM audit_events ORDER BY id DESC LIMIT ?", [limit])


# ---- checkout sessions -------------------------------------------------------------------------------------------
def session(session_id: str) -> dict | None:
    return one("SELECT * FROM checkout_sessions WHERE session_id = ?", [session_id])


def session_by(column: str, value: str) -> dict | None:
    assert column in ("idempotency_key", "paypal_order_id", "capture_id")
    return one(f"SELECT * FROM checkout_sessions WHERE {column} = ?", [value])


def insert_session(s: dict):
    insert("checkout_sessions", s)


def transition(session_id: str, from_status: tuple[str, ...], to_status: str, **fields) -> bool:
    """Compare-and-set: only one caller can move a session out of a given state. Stops double capture."""
    sets = "".join(f", {k} = ?" for k in fields)
    marks = ",".join("?" * len(from_status))
    return run(f"UPDATE checkout_sessions SET status = ?, updated_at = ?{sets} WHERE session_id = ? AND status IN ({marks})",
               [to_status, now(), *fields.values(), session_id, *from_status]) == 1


def units_sold(sku: str) -> int:
    with system():
        return int(one("SELECT coalesce(sum(quantity), 0) n FROM checkout_sessions WHERE sku = ? AND status IN ('CAPTURED','CAPTURING')", [sku])["n"])
